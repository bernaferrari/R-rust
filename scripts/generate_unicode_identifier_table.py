#!/usr/bin/env python3
"""Generate GNU R's wide-alpha intervals from a checked-out R source tree."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess


def generate(source_root: Path) -> str:
    path = source_root / "src/main/rlocale_data.h"
    data = path.read_bytes()
    text = data.decode("utf-8")
    match = re.search(r"table_walpha\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if match is None:
        raise ValueError("GNU R wide-alpha table not found")
    entries = [(int(a, 16), int(b, 16)) for a, b in re.findall(
        r"\{\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\}", match.group(1))]
    if not entries or any(a > b or b > 0x10FFFF for a, b in entries):
        raise ValueError("invalid wide-alpha interval")
    if any(a <= prev_b for (_, prev_b), (a, _) in zip(entries, entries[1:])):
        raise ValueError("wide-alpha intervals overlap or are unordered")
    revision = subprocess.check_output(["git", "-C", str(source_root), "rev-parse", "HEAD"], text=True).strip()
    lines = [
        "// Generated by scripts/generate_unicode_identifier_table.py; do not edit.",
        "// Classification data Copyright (C) 2005-2021 The R Core Team.",
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        f"// Upstream R source commit: {revision}",
        f"// src/main/rlocale_data.h: SHA256 {hashlib.sha256(data).hexdigest()}",
        "#![forbid(unsafe_code)]", "", "pub(super) const R_ALPHA: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{a:x}, 0x{b:x})," for a, b in entries)
    lines.append("];")
    return subprocess.run(["rustfmt", "--edition", "2024", "--config", "skip_children=true"],
                          input="\n".join(lines) + "\n", capture_output=True, text=True, check=True).stdout


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, default=Path("r-source"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path("crates/rmath/src/mainutils/rlocale/identifier_table.rs")
    result = generate(args.source_root)
    if args.check:
        if not output.exists() or output.read_text() != result:
            raise SystemExit(f"{output}: generated data differs")
        print(f"{output}: verified")
    else:
        output.write_text(result)
        print(f"{output}: generated")


if __name__ == "__main__":
    main()
