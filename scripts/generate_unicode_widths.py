#!/usr/bin/env python3
"""Regenerate portable default-locale display widths from the pinned GNU table."""
import argparse
import hashlib
from pathlib import Path
import re

SOURCE_SHA256 = '65957da3b164af6d5c0deaa75de99afc893e2ea385eb419ac858e5b69ef65dd7'


def ranges(values):
    result = []
    for value in sorted(values):
        if result and result[-1][1] + 1 == value:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def generate(source):
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError('unexpected GNU width table hash')
    text = data.decode()
    width_text, zero_text = text.split('static const struct interval zero_width[] =', 1)
    widths = {}
    for first, last, fields in re.findall(r'\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*\{([^}]+)\}\}', width_text):
        first, last = int(first, 16), int(last, 16)
        width = int(fields.split(',')[0])
        if width not in (1, 2) or first > last:
            raise ValueError('invalid GNU width interval')
        for point in range(first, last + 1):
            if point in widths and widths[point] != width:
                raise ValueError('platform branches disagree in default locale')
            widths[point] = width
    zeros = set()
    for first, last in re.findall(r'\{\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)\s*\}', zero_text):
        zeros.update(range(int(first, 16), int(last, 16) + 1))
    # GNU checks the positive-width table first, including its width-one rows.
    zeros.difference_update(widths)
    wide = ranges(point for point, width in widths.items() if width == 2)
    zero = ranges(zeros)
    if not wide or not zero:
        raise ValueError('empty GNU width tables')
    out = ['// Generated by scripts/generate_unicode_widths.py; do not edit.',
           '// Copyright (C) 2005-2021 The R Core Team',
           '// SPDX-License-Identifier: GPL-2.0-or-later; see repository LICENSE.',
           '// rlocale_widths.h at d4cc5d9e196a144bbb087a798bb945b37121383b',
           '// is byte-identical at oracle bac583951b728e97b9786804d3b4081f0fe18df5.',
           '// Source SHA-256: ' + SOURCE_SHA256, '']
    for name, rows in [('WIDE', wide), ('ZERO', zero)]:
        out.append('pub(super) const ' + name + ': &[(u32, u32)] = &[')
        out.extend(f'    (0x{first:X}, 0x{last:X}),' for first, last in rows)
        out.append('];\n')
    return '\n'.join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=Path('r-source/src/main/rlocale_widths.h'))
    p.add_argument('--output', type=Path, default=Path('crates/rmath/src/mainutils/unicode_width/tables.rs'))
    args = p.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(args.source))


if __name__ == '__main__':
    main()
