#!/usr/bin/env python3
"""Generate GNU R's portable wide-character class intervals."""
import argparse
import hashlib
from pathlib import Path
import re
import subprocess


CLASSES = ("upper", "lower", "xdigit", "space", "print", "blank", "cntrl", "punct")
PAIR = re.compile(r"\{\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\}\s*,?")


def generate(source_root: Path) -> str:
    data = (source_root / "src/main/rlocale_data.h").read_bytes()
    text = data.decode("utf-8")
    revision = subprocess.check_output(["git", "-C", str(source_root), "rev-parse", "HEAD"], text=True).strip()
    lines = ["// Generated by scripts/generate_unicode_wctype_tables.py; do not edit.",
             "// Classification data Copyright (C) 2005-2021 The R Core Team.",
             "// SPDX-License-Identifier: GPL-2.0-or-later",
             f"// Upstream R source commit: {revision}",
             f"// src/main/rlocale_data.h: SHA256 {hashlib.sha256(data).hexdigest()}",
             "#![forbid(unsafe_code)]"]
    for name in CLASSES:
        match = re.search(r"table_w" + name + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
        if match is None:
            raise ValueError(f"missing wide-character class: {name}")
        body = re.sub(r"/\*.*?\*/|//[^\n]*", "", match.group(1), flags=re.S)
        pairs = [(int(a, 16), int(b, 16)) for a, b in PAIR.findall(body)]
        if PAIR.sub("", body).strip() or not pairs:
            raise ValueError(f"unrecognized wide-character class data: {name}")
        if any(a > b or b > 0x10FFFF for a, b in pairs) or any(
            a <= prev_b for (_, prev_b), (a, _) in zip(pairs, pairs[1:])
        ):
            raise ValueError(f"invalid or unordered wide-character intervals: {name}")
        lines.extend(["", f"pub(super) const {name.upper()}: &[(u32, u32)] = &["])
        lines.extend(f"    (0x{a:x}, 0x{b:x})," for a, b in pairs)
        lines.append("];")
    return subprocess.run(["rustfmt", "--edition", "2024", "--config", "skip_children=true"],
                          input="\n".join(lines) + "\n", capture_output=True, text=True, check=True).stdout


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, default=Path("r-source"))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = Path("crates/rmath/src/mainutils/rlocale/wctype_tables.rs")
    result = generate(args.source_root)
    if args.check:
        if not output.exists() or output.read_text() != result:
            raise SystemExit(f"{output}: generated data differs")
        print(f"{output}: verified")
    else:
        output.write_text(result)
        print(f"{output}: generated")


if __name__ == "__main__":
    main()
