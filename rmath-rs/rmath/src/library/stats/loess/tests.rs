use super::*;
fn config(interpolate: bool, exact: bool) -> Config {
    Config {
        span: 0.75,
        degree: 2,
        normalize: true,
        parametric: vec![false],
        drop_square: vec![false],
        interpolate,
        cell: 0.2,
        iterations: 1,
        exact,
        approximate_trace: false,
    }
}
fn close(a: f64, b: f64) {
    assert!((a - b).abs() < 2e-10, "{a} != {b}");
}
