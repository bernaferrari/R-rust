/// Compute x * log(x / M) + (M - x)
/// aka -x * log1pmx((M - x) / x)
///
/// Deliver the result back in two parts, yh and yl.
pub(crate) fn ebd0(x: f64, m: f64) -> (f64, f64) {
    const SB: i32 = 10;
    const S: f64 = (1u32 << SB) as f64; // = 2^10 = 1024
    const N: i32 = 128; // == G_N_ELEMENTS(bd0_scale) - 1

    let mut yh: f64 = 0.0;
    let mut yl: f64 = 0.0;

    if x == m {
        return (yh, yl);
    }
    if x == 0.0 {
        yh = m;
        return (yh, yl);
    }
    if m == 0.0 {
        yh = ML_POSINF;
        return (yh, yl);
    }

    if m / x == ML_POSINF {
        yh = m;
        return (yh, yl);
    } // as when (x == 0)

    // NB: M/x overflow handled above; underflow should be handled by fg = Inf
    let (r, e) = frexp(m / x); // => r in [0.5, 1) and 'e' (int) such that M/x = r * 2^e

    // prevent later overflow
    if M_LN2 * (-(e as f64)) > 1.0 + f64::MAX / x {
        yh = ML_POSINF;
        return (yh, yl);
    }

    let i = floor((r - 0.5) * (2.0 * N as f64) + 0.5) as i32;
    // now, 0 <= i <= N
    let f = floor(S / (0.5 + i as f64 / (2.0 * N as f64)) + 0.5);
    let fg = ldexp(f, -(e + SB)); // ldexp(f, E) := f * 2^E

    if fg == ML_POSINF {
        yh = fg;
        return (yh, yl);
    }

    // ADD1 macro
    let mut add1 = |d_: f64| -> bool {
        let d = d_; // volatile in C, but Rust doesn't have volatile locals easily
        let d1 = floor(d + 0.5);
        let d2 = d - d1; // in [-.5,.5)
        yh += d1;
        yl += d2;
        r_finite(yh)
    };

    if !add1(-x * log1pmx((m * fg - x) / x)) {
        yh = ML_POSINF;
        yl = 0.0;
        return (yh, yl);
    }

    if fg == 1.0 {
        return (yh, yl);
    }

    // else (fg != 1) :
    for j in 0..4 {
        if !add1(x * BD0_SCALE[i as usize][j]) {
            // handles  x*log(fg*2^e)
            yh = ML_POSINF;
            yl = 0.0;
            return (yh, yl);
        }
        if !add1(-x * BD0_SCALE[0][j] * e as f64) {
            // handles  x*log(1/2^e)
            //                    ^^^ at end prevents overflow in ebd0(1e307, 1e300)
            yh = ML_POSINF;
            yl = 0.0;
            return (yh, yl);
        }
    }

    add1(m);
    add1(-m * fg);

    (yh, yl)
}

pub extern "C" fn Rf_bd0(x: f64, np: f64) -> f64 {
    bd0(x, np)
}
