const DBL_MIN: f64 = 2.2250738585072014e-308;
const M_LN2: f64 = 0.693147180559945309417232121458; // log(2)

/// Evaluates the "deviance part"
/// bd0(x,M) := M * D0(x/M) = M*[ x/M * log(x/M) + 1 - (x/M) ] = x * log(x/M) + M - x
/// where M = E[X] = n*p (or = lambda), for x, M > 0
///
/// in a manner that should be stable (with small relative error)
/// for all x and M=np. In particular for x/np close to 1, direct
/// evaluation fails, and evaluation is based on the Taylor series
/// of log((1+v)/(1-v)) with v = (x-M)/(x+M) = (x-np)/(x+np).
pub(crate) fn bd0(x: f64, np: f64) -> f64 {
    if !r_finite(x) || !r_finite(np) || np == 0.0 {
        return f64::NAN;
    }

    if fabs(x - np) < 0.1 * (x + np) {
        let d = x - np;
        let mut v = d / (x + np);
        if (d != 0.0) && (v == 0.0) {
            // v has underflown to 0 (as x+np = inf)
            let x_ = ldexp(x, -2);
            let n_ = ldexp(np, -2);
            v = (x_ - n_) / (x_ + n_);
        }
        let mut s = ldexp(d, -1) * v; // was d * v
        if fabs(ldexp(s, 1)) < DBL_MIN {
            return ldexp(s, 1);
        }
        let mut ej = x * v; // as 2*x*v could overflow: v > 1/2 ==> ej = 2xv > x
        v *= v; // "v = v^2"
        let mut j: i32 = 1;
        while j < 1000 {
            // Taylor series; 1000: no infinite loop as |v| < .1, v^2000 is "zero"
            ej *= v; // = x v^(2j+1)
            let s_ = s;
            s += ej / (((j << 1) + 1) as f64);
            if s == s_ {
                // last term was effectively 0
                return ldexp(s, 1); // 2*s ; as we dropped '2 *' above
            }
            j += 1;
        }
        // the following should _never_ happen
        // MATHLIB_WARNING4("bd0(%g, %g): T.series failed to converge in 1000 it.; s=%g, ej/(2j+1)=%g\n",
        //                  x, np, s, ej/((1000<<1)+1));
    }
    // else: |x - np| is not too small
    // NB: x/np |--> inf (overflow) doesn't happen when called from rpois_raw()
    let lg_x_n = if r_finite(x / np) {
        log(x / np)
    } else {
        log(x) - log(np)
    };
    if x > np {
        x * (lg_x_n - 1.0) + np
    } else {
        x * lg_x_n + np - x
    }
}

