payload <- list(a = 1:2)
raw2 <- serialize(payload, NULL, version = 2)
raw3 <- serialize(payload, NULL, version = 3)
cat(typeof(raw2), "\n", sep = "")
cat(typeof(raw3), "\n", sep = "")
cat(length(raw2) > 0, "\n", sep = "")
cat(length(raw3) > 0, "\n", sep = "")
cat(identical(unserialize(raw2), payload), "\n", sep = "")
cat(identical(unserialize(raw3), payload), "\n", sep = "")
cat(identical(raw2, raw3), "\n", sep = "")
r2 <- serialize(1:2, NULL, FALSE, TRUE, version = 2)
r3 <- serialize(1:2, NULL, FALSE, TRUE, version = 3)
cat(identical(unserialize(r2), 1:2), "\n", sep = "")
cat(identical(unserialize(r3), 1:2), "\n", sep = "")
cat(!identical(r2, r3), "\n", sep = "")
