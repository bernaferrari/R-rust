## Curated from r-source/tests/complex.R:
## complex literal parsing and arithmetic identities.
options(digits = 7)

print(1i)
print(0i)
print(1 + 2i)

z <- as.complex(c(1, 2)) + as.complex(c(3, 4))
print(z)
print(typeof(z))

z <- as.complex(c(1, 2)) * as.complex(c(3, 4))
print(z)
print(typeof(z))

z <- c(1+2i, -3+4i, 0+1i)
print(z)
print(typeof(z))
print(all(abs(Re(z^2) - c(-3, -7, -1)) < 1e-6))
print(all(abs(Im(z^2) - c(4, -24, 0)) < 1e-6))
print(all(abs(Re(sqrt(z)) - c(1.27201965, 1.0, 0.70710678)) < 1e-5))
print(all(abs(Im(sqrt(z)) - c(0.78615138, 2.0, 0.70710678)) < 1e-5))
print(all(abs(Re(exp(z)) - c(-1.13120438, -0.03254299, 0.54030231)) < 1e-5))
print(all(abs(Im(exp(z)) - c(2.47172667, -0.03767898, 0.84147098)) < 1e-5))
print(all(abs(Re(log(z)) - c(0.80471896, 1.60943791, 0.0)) < 1e-5))
print(all(abs(Im(log(z)) - c(1.10714872, 2.21429744, 1.57079633)) < 1e-5))
print(all(abs(Re(sin(z)) - c(3.16577851, -3.85373804, 0.0)) < 1e-5))
print(all(abs(Im(sin(z)) - c(1.95960104, -27.01681326, 1.17520119)) < 1e-5))
print(all(abs(Re(cos(z)) - c(2.03272301, -27.0349456, 1.54308063)) < 1e-5))
print(all(abs(Im(cos(z)) - c(-3.0518978, 3.85115333, 0.0)) < 1e-5))
print(all(abs(Re(tan(z)) - c(0.03381283, 0.00018735, 0.0)) < 1e-5))
print(all(abs(Im(tan(z)) - c(1.01479362, 0.99935599, 0.76159416)) < 1e-5))
print(all(abs(Mod(z) - c(2.23606798, 5.0, 1.0)) < 1e-5))
print(all(abs(Arg(z) - c(1.10714872, 2.21429744, 1.57079633)) < 1e-5))
