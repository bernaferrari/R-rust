# Independent immutable GNU package image; never run the Rust runtime here.
args <- commandArgs(TRUE)
stopifnot(length(args) == 1L, identical(as.character(getRversion()), "4.7.0"), identical(R.version[["svn rev"]], "90451"))
out <- args[[1L]]
dir.create(out, recursive=TRUE, showWarnings=FALSE)
p <- system.file(package="methods")
stopifnot(nzchar(p))
stopifnot(file.copy(file.path(p,"R","methods.rdb"), file.path(out,"methods.rdb"), overwrite=TRUE))
index <- readRDS(file.path(p,"R","methods.rdx"))
saveRDS(index,file.path(out,"index.rds"),version=2,compress=FALSE)
saveRDS(sort(getNamespaceExports("methods")),file.path(out,"exports.rds"),version=2,compress=FALSE)
info <- get(".__NAMESPACE__.",asNamespace("methods"))
saveRDS(get("S3methods",info),file.path(out,"S3methods.rds"),version=2,compress=FALSE)
for (name in c("DESCRIPTION","NAMESPACE")) stopifnot(file.copy(file.path(p,name),file.path(out,name),overwrite=TRUE))
assignments <- as.list(body(base:::lazyLoadDBexec))
selected <- Filter(function(x) is.call(x) && identical(x[[1L]],as.name("<-")) && identical(x[[2L]],as.name("envhook")),assignments)
stopifnot(length(selected)==1L)
dput(selected[[1L]][[3L]],file=file.path(out,"envhook.R"))
cat("Pinned GNU", R.version$platform, "variables",length(index$variables),"references",length(index$references),"exports",length(getNamespaceExports("methods")),"\n")
