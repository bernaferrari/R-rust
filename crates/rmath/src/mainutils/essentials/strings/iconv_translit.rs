#![forbid(unsafe_code)]
/// macOS libiconv's Latin-1 supplement transliterations for
/// `ASCII//TRANSLIT` (0xA0-0xFF). `None` marks code points iconv cannot
/// transliterate.
pub(super) fn ascii_translit(cp: u32) -> Option<&'static str> {
    Some(match cp {
        0xA0 => " ",
        0xA1 => "!",
        0xA2 => "c",
        0xA3 => "lb",
        0xA4 => return None,
        0xA5 => "yen",
        0xA6 => "|",
        0xA7 => "SS",
        0xA8 => "\"",
        0xA9 => "(c)",
        0xAA => "a",
        0xAB => "<<",
        0xAC => "not",
        0xAD => "-",
        0xAE => "(R)",
        0xAF => return None,
        0xB0 => "^0",
        0xB1 => "+/-",
        0xB2 => "^2",
        0xB3 => "^3",
        0xB4 => "'",
        0xB5 => "u",
        0xB6 => "P",
        0xB7 => ".",
        0xB8 => ",",
        0xB9 => "^1",
        0xBA => "o",
        0xBB => ">>",
        0xBC..=0xBF => return None,
        0xC0 => "`A",
        0xC1 => "'A",
        0xC2 => "^A",
        0xC3 => "~A",
        0xC4 => "\"A",
        0xC5 => "A",
        0xC6 => "AE",
        0xC7 => "C",
        0xC8 => "`E",
        0xC9 => "'E",
        0xCA => "^E",
        0xCB => "\"E",
        0xCC => "`I",
        0xCD => "'I",
        0xCE => "^I",
        0xCF => "\"I",
        0xD0 => "D",
        0xD1 => "~N",
        0xD2 => "`O",
        0xD3 => "'O",
        0xD4 => "^O",
        0xD5 => "~O",
        0xD6 => "\"O",
        0xD7 => "x",
        0xD8 => "O",
        0xD9 => "`U",
        0xDA => "'U",
        0xDB => "^U",
        0xDC => "\"U",
        0xDD => "'Y",
        0xDE => "Th",
        0xDF => "ss",
        0xE0 => "`a",
        0xE1 => "'a",
        0xE2 => "^a",
        0xE3 => "~a",
        0xE4 => "\"a",
        0xE5 => "a",
        0xE6 => "ae",
        0xE7 => "c",
        0xE8 => "`e",
        0xE9 => "'e",
        0xEA => "^e",
        0xEB => "\"e",
        0xEC => "`i",
        0xED => "'i",
        0xEE => "^i",
        0xEF => "\"i",
        0xF0 => "d",
        0xF1 => "~n",
        0xF2 => "`o",
        0xF3 => "'o",
        0xF4 => "^o",
        0xF5 => "~o",
        0xF6 => "\"o",
        0xF7 => ":",
        0xF8 => "o",
        0xF9 => "`u",
        0xFA => "'u",
        0xFB => "^u",
        0xFC => "\"u",
        0xFD => "'y",
        0xFE => "th",
        0xFF => "\"y",
        _ => return None,
    })
}
